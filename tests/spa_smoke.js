#!/usr/bin/env node
'use strict';
// tests/spa_smoke.js — C1/C2 (0.9.0): render-everything smoke test for the
// delivered SPA.
//
// C1: dependency-free node test — a minimal fake DOM (elements record
// innerHTML; a fetch that returns canned fixtures) imports the delivered
// SPA script (the exact script the browser receives: static/app.js, a
// real file since the G8 split) and invokes every top-level view renderer against
// fixture company data, asserting no exception, non-empty HTML, and no
// literal 'undefined'/'NaN' in the rendered output. node --check catches
// syntax errors (0.8.1); call-resolution catches unresolved names (0.8.2);
// this catches the third class — field access on real data shapes.
//
// C2: the canned fetch responses (manifest.json per fixture tree) are
// generated by running this same runner in --mode record against the REAL
// dashboard server pointed at the shared fixture tree — one fixture set,
// two consumers. A server-side field rename changes the recorded manifest,
// so the committed fixture drifts from the live server and the CI re-record
// comparison fails (and a renderer that now reads the renamed field renders
// literal 'undefined', failing the content invariant in replay too).
//
// Usage:
//   record:  node tests/spa_smoke.js --server <server.js> --mode record \
//               --tree <company-dir> --base http://127.0.0.1:PORT \
//               --root <project-root> --out <manifest.json> [--report <file>]
//   replay:  node tests/spa_smoke.js --server <server.js> --mode replay \
//               --fixtures <manifest.json> [--root-sub <placeholder>=<value>] \
//               [--report <file>]
//
// Exit 0 = every view rendered cleanly; exit 1 with a JSON report otherwise.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

// ── args ────────────────────────────────────────────────────────────────
const args = process.argv.slice(2);
const arg = (name, dflt) => {
  const i = args.indexOf(name);
  return i >= 0 && i + 1 < args.length ? args[i + 1] : dflt;
};
const SERVER_JS = arg('--server');
const MODE = arg('--mode');            // record | replay
const TREE = arg('--tree', '');
const BASE = arg('--base', '');
const ROOT = arg('--root', '');        // record: project root to placeholder-ize
const OUT = arg('--out', '');
const FIXTURES = arg('--fixtures', '');
const ROOT_SUB = arg('--root-sub', '');
const REPORT = arg('--report', '');
if (!SERVER_JS || !MODE || (MODE === 'record' && (!TREE || !BASE || !OUT)) ||
    (MODE === 'replay' && !FIXTURES)) {
  console.error('bad arguments — see the header of spa_smoke.js');
  process.exit(2);
}

// ── extract the delivered SPA script (what the browser RECEIVES) ────────
// The SPA lives in server.js as a JS template literal. Re-evaluating the
// same template source in node reproduces the string the server builds
// and serves (escape processing included) — the same trick the 0.8.1
// regression test uses.
function extractDeliveredScript(serverJsPath) {
  // G8: the SPA is real files served from disk — no template literal
  // to un-eval. The delivered script IS static/app.js.
  const dir = path.dirname(serverJsPath);
  const p = path.join(dir, 'static', 'app.js');
  if (!fs.existsSync(p)) throw new Error('static/app.js not found (G8 split) in ' + dir);
  return fs.readFileSync(p, 'utf8');
}

// ── fake DOM: explicit surface, unknown properties -> undefined (exactly
// what a real DOM element returns) ───────────────────────────────────────
class ClassList {
  constructor() { this.s = new Set(); }
  add(...c) { c.forEach((x) => this.s.add(x)); }
  remove(...c) { c.forEach((x) => this.s.delete(x)); }
  toggle(c, f) {
    if (f === undefined) f = !this.s.has(c);
    if (f) this.s.add(c); else this.s.delete(c);
    return f;
  }
  contains(c) { return this.s.has(c); }
}

class FakeElement {
  constructor(tag, id) {
    this.tagName = String(tag || 'div').toUpperCase();
    this.id = id || '';
    this.children = [];
    this.style = {};
    this.classList = new ClassList();
    this.dataset = {};
    this.attributes = {};
    this.value = '';
    this.textContent = '';
    this._innerHTML = '';
    this.scrollTop = 0; this.scrollLeft = 0;
    this.scrollHeight = 0; this.clientHeight = 0;
    this.offsetWidth = 0; this.offsetHeight = 0;
    this.selectionStart = 0; this.selectionEnd = 0;
    this.disabled = false; this.checked = false;
    this.options = [];
  }
  get innerHTML() { return this._innerHTML; }
  set innerHTML(v) {
    FakeElement.__recordSet(this, String(v));
    this._innerHTML = String(v);
  }
  focus() {}
  blur() {}
  click() {}
  select() {}
  setSelectionRange() {}
  getAttribute(n) { return this.attributes[n] !== undefined ? this.attributes[n] : null; }
  setAttribute(n, v) { this.attributes[n] = String(v); }
  appendChild(x) { this.children.push(x); return x; }
  removeChild(x) { this.children = this.children.filter((c) => c !== x); return x; }
  insertBefore(n) { this.children.unshift(n); return n; }
  remove() {}
  addEventListener() {}
  removeEventListener() {}
  querySelector() { return null; }
  querySelectorAll() { return []; }
  contains() { return false; }
  getBoundingClientRect() { return { left: 0, top: 0, right: 0, bottom: 0, width: 0, height: 0 }; }
  insertAdjacentHTML() {}
  cloneNode() { return new FakeElement(this.tagName, this.id); }
  get firstChild() { return this.children[0] || null; }
  get lastChild() { return this.children[this.children.length - 1] || null; }
}

const elements = new Map();
const elById = (id) => {
  if (!elements.has(id)) elements.set(id, new FakeElement('div', id));
  return elements.get(id);
};

const fakeDocument = {
  readyState: 'complete',
  title: '',
  activeElement: null,
  body: new FakeElement('body'),
  head: new FakeElement('head'),
  getElementById: (id) => elById(id),
  querySelector: () => null,
  querySelectorAll: () => [],
  createElement: (t) => new FakeElement(t),
  createTextNode: (t) => ({ textContent: String(t) }),
  addEventListener() {},
  removeEventListener() {},
};

// ── fetch: record against the live server, or replay from the manifest ──
const manifest = { responses: {} };
if (MODE === 'replay') {
  const m = JSON.parse(fs.readFileSync(FIXTURES, 'utf8'));
  manifest.responses = m.responses || {};
  if (ROOT_SUB) {
    const [ph, val] = ROOT_SUB.split('=');
    for (const [k, v] of Object.entries(manifest.responses)) {
      v.body = JSON.parse(String(JSON.stringify(v.body)).split(ph).join(val));
    }
  }
}
const misses = [];
const recordedUrls = [];

function makeResponse(status, bodyText) {
  let parsed = null;
  try { parsed = JSON.parse(bodyText); } catch { parsed = { error: 'unparseable response: ' + String(bodyText).slice(0, 200) }; }
  return {
    status,
    ok: status >= 200 && status < 400,
    text: async () => bodyText,
    json: async () => parsed,
  };
}

async function fakeFetch(url, opts) {
  const key = String(url).replace(/^\/api\//, '');
  if (MODE === 'record') {
    const r = await fetch(BASE + '/api/' + key, opts);
    const text = await r.text();
    manifest.responses[key] = { status: r.status, body: JSON.parse(text || 'null') };
    recordedUrls.push(key);
    return makeResponse(r.status, text);
  }
  const rec = manifest.responses[key];
  if (!rec) { misses.push(key); return makeResponse(200, JSON.stringify({})); }
  return makeResponse(rec.status, JSON.stringify(rec.body));
}

// ── the vm context ──────────────────────────────────────────────────────
const alerts = [];
const storage = {};
const unhandled = [];
// An async view can reject WITHOUT being awaited (openGlobalStream fires
// refreshGlobalStream and returns). Node >= 15 kills the process on
// unhandled rejections — capture them as smoke failures instead, with
// the stack naming the offending view, and let the run continue.
process.on('unhandledRejection', (e) => {
  unhandled.push(e && e.stack ? String(e.stack).split('\n').slice(0, 4).join(' | ') : String(e));
});
let renderedSinceMark = [];
FakeElement.__recordSet = (elm, v) => { renderedSinceMark.push({ id: elm.id || elm.tagName, bytes: v.length, html: v }); };

const sandbox = {
  console,
  document: fakeDocument,
  fetch: fakeFetch,
  alert: (m) => alerts.push(String(m)),
  confirm: () => false,
  prompt: () => null,
  location: { hash: '', href: 'http://localhost/', reload() {} },
  localStorage: {
    getItem: (k) => (k in storage ? storage[k] : null),
    setItem: (k, v) => { storage[k] = String(v); },
    removeItem: (k) => { delete storage[k]; },
  },
  addEventListener() {},
  removeEventListener() {},
  scrollX: 0, scrollY: 0,
  innerWidth: 1200, innerHeight: 800,
  scrollTo() {},
  scrollBy() {},
  setTimeout: (fn, ms, ...a) => setTimeout(fn, Math.min(ms || 0, 2000), ...a),
  clearTimeout: (id) => clearTimeout(id),
  setInterval: (fn, ms, ...a) => setInterval(fn, Math.max(ms || 1000, 1000), ...a),
  clearInterval: (id) => clearInterval(id),
};
sandbox.window = sandbox;
sandbox.self = sandbox;

// EventSource: real shape, no live connection — onopen/onmessage/onerror
// never fire, so SSE-driven refreshes stay dormant.
class FakeEventSource {
  constructor(url) { this.url = url; this.readyState = 0; this.onopen = null; this.onmessage = null; this.onerror = null; }
  close() { this.readyState = 2; }
  addEventListener() {}
  removeEventListener() {}
}
sandbox.EventSource = FakeEventSource;

vm.createContext(sandbox);

// ── view list: every top-level view renderer (C1) ───────────────────────
// fn: a name on the context, or an arrow taking the context (for views
// that take arguments — worktree/diff/branch/commit are driven by data
// read from the 'git' response so record and replay always agree).
const VIEWS = [
  ['dashboard', 'showDashboard'],
  ['sprint', 'showSprint'],
  ['chats', 'showChats'],
  ['roster', 'showRoster'],
  ['org-chart', 'showOrgChart'],
  ['reports', 'showReports'],
  ['recommendations', 'showReportsRecommendations'],
  ['processes', 'showProcesses'],
  ['rounds', 'showRounds'],
  ['github', 'showGitHub'],
  ['releases', 'showReleases'],
  ['git', 'showGit'],
  ['worktree', (ctx) => {
    const git = (manifest.responses['git'] || {}).body || {};
    const wt = (git.worktrees || []).find((w) => !w.isMain) || (git.worktrees || [])[0] || {};
    ctx.showWorktree(wt.ticket || wt.branch || 'wt', wt.path || '', wt.branch || 'main', wt.ticket || '', (wt.head || '00000000').slice(0, 8), !!wt.isMain);
    // showWorktree fires loadWorktreeFiles without awaiting it — await an
    // identical call so the files list actually renders before we assert.
    return ctx.loadWorktreeFiles('');
  }],
  ['worktree-changes', (ctx) => {
    ctx.switchWtTab('changes');
    return ctx.loadWorktreeDiff();
  }],
  ['branch-history', (ctx) => {
    const git = (manifest.responses['git'] || {}).body || {};
    // git prefixes worktree-checked-out branches with '+ ' in `git branch`
    // output; the server passes that marker through — strip it to browse
    // the real branch.
    const b = (git.branches || []).map((x) => String(x).replace(/^[*+]\s+/, '').trim())
      .find((x) => x !== 'main' && x !== 'master') || 'main';
    return ctx.showBranchHistory(b, true);
  }],
  ['commit-diff', (ctx) => {
    const git = (manifest.responses['git'] || {}).body || {};
    const log = git.log || [];
    return ctx.showCommitDiff((log[0] || {}).hash || 'missing', true);
  }],
  ['activity', 'showActivity'],
  ['global-stream', (ctx) => {
    ctx.openGlobalStream();
    // openGlobalStream already fired refreshGlobalStream (un-awaited); a
    // second call defers via the pending flag while the first is in
    // flight. Poll until its render lands instead of awaiting the no-op.
    return new Promise((resolve) => {
      const started = Date.now();
      const timer = setInterval(() => {
        if (renderedSinceMark.length > 0 || Date.now() - started > 10000) {
          clearInterval(timer);
          resolve();
        }
      }, 25);
    });
  }],
  ['verification', (ctx) => {
    ctx.showVerification();
    return ctx.renderVerification();
  }],
  ['brief', 'showBrief'],
  ['marketing', 'showMarketing'],
  ['config', 'showConfig'],
  ['connect', 'showConnect'],
];

// 'undefined'/'NaN' as rendered text = a field the data shape doesn't
// carry (the rename class). Wholde-word-ish check on the visible text.
function badTokens(html) {
  const out = [];
  for (const tok of ['undefined', 'NaN']) {
    const re = new RegExp('(?<![\\w-])' + tok + '(?![\\w-])', 'g');
    if (re.test(html)) out.push(tok);
  }
  return out;
}

async function main() {
  const spa = extractDeliveredScript(SERVER_JS);
  vm.runInContext(spa, sandbox, { filename: 'spa-delivered.js' });

  // Load-time path (checkStatus) is fire-and-forget — let it settle.
  await new Promise((r) => setTimeout(r, MODE === 'replay' ? 300 : 1500));

  const viewResults = [];
  let failed = false;
  for (const [name, fn] of VIEWS) {
    renderedSinceMark = [];
    let err = null;
    try {
      const p = typeof fn === 'string' ? sandbox[fn]() : fn(sandbox);
      if (p && typeof p.then === 'function') await p;
    } catch (e) {
      err = e && e.stack ? String(e.stack).split('\n').slice(0, 3).join(' | ') : String(e);
    }
    const rendered = renderedSinceMark.length;
    const maxBytes = renderedSinceMark.reduce((m, x) => Math.max(m, x.bytes), 0);
    const bad = [];
    for (const chunk of renderedSinceMark) bad.push(...badTokens(chunk.html));
    const ok = !err && rendered > 0 && maxBytes >= 10 && bad.length === 0;
    if (!ok) failed = true;
    viewResults.push({
      name,
      ok,
      error: err || null,
      rendered_elements: rendered,
      max_rendered_bytes: maxBytes,
      bad_tokens: [...new Set(bad)],
    });
    // A throwing view leaves the context usable; keep going so one bad
    // view doesn't hide the other nineteen.
  }

  const report = {
    mode: MODE,
    ok: !failed && misses.length === 0 && unhandled.length === 0,
    views: viewResults,
    misses,
    unhandled,
    alerts: [...new Set(alerts)],
  };
  const reportText = JSON.stringify(report, null, 2);
  if (REPORT) fs.writeFileSync(REPORT, reportText);

  if (MODE === 'record') {
    // Normalize volatile fields so the manifest is stable across machines
    // and tmp dirs: absolute project roots become <PROJECT_ROOT>, and the
    // server start time (status.started_at) is zeroed.
    if (ROOT) {
      for (const k of Object.keys(manifest.responses)) {
        const b = manifest.responses[k].body;
        if (k === 'status' && b && typeof b === 'object' && 'started_at' in b) b.started_at = 0;
      }
      let manText = JSON.stringify(manifest, null, 2);
      manText = manText.split(ROOT).join('<PROJECT_ROOT>');
      fs.mkdirSync(path.dirname(OUT), { recursive: true });
      fs.writeFileSync(OUT, manText);
    } else {
      fs.mkdirSync(path.dirname(OUT), { recursive: true });
      fs.writeFileSync(OUT, JSON.stringify(manifest, null, 2));
    }
  }

  console.log(reportText);
  process.exit(report.ok ? 0 : 1);
}

main().catch((e) => {
  const report = { mode: MODE, ok: false, fatal: e && e.stack ? String(e.stack) : String(e), views: [] };
  if (REPORT) fs.writeFileSync(REPORT, JSON.stringify(report, null, 2));
  console.error(JSON.stringify(report, null, 2));
  process.exit(1);
});
