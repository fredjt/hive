#!/usr/bin/env bash
set -euo pipefail

# init-legal-scaffold.sh - Create the project's <project_root>/legal/ tree
# for legal department deliverables.
#
# Outside .company/ because these are real shippable artifacts (privacy
# policy, ToS, license inventory) that the user will want to commit and
# eventually publish on the product's website.
#
# Idempotent: existing files are not overwritten.

if [ $# -lt 1 ]; then
  echo "Usage: init-legal-scaffold.sh <project-root>" >&2
  exit 1
fi

PROJECT_ROOT="$(cd "$1" && pwd)"
L_DIR="$PROJECT_ROOT/legal"

mkdir -p "$L_DIR/compliance"

DRAFT_BANNER='> **DRAFT** — Generated by Hive'"'"'s VP-Legal agent. Review by qualified
> counsel required before publication or relying on this for any legal purpose.
'

write_if_missing() {
  local path="$1" content="$2"
  [ -f "$path" ] && return
  printf '%s\n' "$content" > "$path"
  echo "  + $path" >&2
}

write_if_missing "$L_DIR/privacy.md" "$DRAFT_BANNER
# Privacy Policy

> Updated by VP-Legal each cycle as the product changes how it handles user data.

## Information we collect
- TBD: enumerate every field collected from users

## Purpose / lawful basis
- TBD: per GDPR Article 6, name the basis (consent, contract, legitimate interest, etc.)

## Retention
- TBD: how long do we keep each category of data?

## Sharing
- TBD: vendors / sub-processors / law enforcement requests

## Your rights
- Access (GDPR Art. 15) — TBD: how to request
- Rectification (Art. 16) — TBD
- Erasure (Art. 17) — TBD
- Portability (Art. 20) — TBD
- Object (Art. 21) — TBD

## Contact
- TBD: privacy@yourdomain

## Changes
- We will notify users of material changes ≥30 days in advance.
"

write_if_missing "$L_DIR/terms.md" "$DRAFT_BANNER
# Terms of Service

## Acceptance
By using the Service, you agree to these terms.

## Account
- TBD: account creation, eligibility, security responsibilities

## Acceptable use
- TBD: prohibited activities

## Intellectual property
- TBD: who owns what; user-generated content licensing back to us

## Fees
- TBD: see /pricing for current pricing

## Termination
- TBD: cancellation policy, data export window

## Disclaimers
- Provided AS IS, without warranty of any kind.

## Limitation of liability
- TBD: liability cap

## Indemnification
- TBD

## Governing law
- TBD: which jurisdiction

## Changes
- We may update these terms; material changes notified ≥30 days in advance.
"

write_if_missing "$L_DIR/licenses.md" "$DRAFT_BANNER
# Dependency License Inventory

> Auto-walked by VP-Legal each cycle. Compatibility checked against our product license (see ./LICENSE).

| Dependency | Version | License | Compatible? | Notes |
|------------|---------|---------|-------------|-------|
| (TBD) | | | | |

## Compatibility rules of thumb
- MIT / Apache 2.0 / BSD: compatible with almost everything
- GPL / AGPL: forces our product to also be GPL/AGPL if linked
- Commercial / proprietary: check terms before shipping

## Action items
- (none yet)
"

write_if_missing "$L_DIR/risk-register.md" "$DRAFT_BANNER
# Legal & Compliance Risk Register

| Risk | Severity | Likelihood | Owner | Mitigation | Status |
|------|----------|-----------|-------|------------|--------|
| User data leak | HIGH | LOW | IT | Bucket policies, security review | open |
| Missing privacy policy at launch | HIGH | MEDIUM | Legal | Ship privacy.md before launch | open |
| Open-source license incompatibility | MEDIUM | MEDIUM | Legal | Quarterly license audit | open |
| Terms claim what product can't deliver | MEDIUM | LOW | Legal+Marketing | Cross-review claims | open |
"

write_if_missing "$L_DIR/dpa-template.md" "$DRAFT_BANNER
# Data Processing Addendum (Template)

> Provided to enterprise customers when they need a DPA for GDPR Art. 28.
> Customize jurisdiction, data categories, sub-processors before sending.

## Definitions
## Subject matter & duration of processing
## Nature & purpose
## Categories of data subjects & data
## Sub-processors
- TBD: list each (Anthropic, AWS, Stripe, etc.) with location and purpose
## Security measures
## Data subject rights cooperation
## Audit rights
## International transfers
## Termination & data return/deletion
"

write_if_missing "$L_DIR/CLA.md" "$DRAFT_BANNER
# Contributor License Agreement (or DCO)

> Required if accepting outside contributions. Choose ONE:
> - Use the Developer Certificate of Origin (DCO) — lightweight, sign-off in commits
> - Use a CLA — heavier, signed agreement per contributor
"

# Compliance frameworks - empty scaffolds; VP-Legal fills in only the relevant ones
write_if_missing "$L_DIR/compliance/GDPR.md" "$DRAFT_BANNER
# GDPR Compliance Posture

(Only fill in if the product has EU users.)

## Are we a controller or processor?
## Lawful basis per data category
## Article-by-article posture
## Outstanding gaps
"
write_if_missing "$L_DIR/compliance/CCPA.md" "$DRAFT_BANNER
# CCPA Compliance Posture

(Only fill in if the product has California users.)

## Categories of personal information collected
## Sources
## Business purposes
## Sale/sharing — do we sell? if not, state clearly.
## Consumer rights — how exercised
"
write_if_missing "$L_DIR/compliance/SOC2.md" "$DRAFT_BANNER
# SOC 2 Readiness

(Only fill in if pursuing SOC 2 — usually for enterprise sales.)

## Trust services criteria scope
## Current control maturity (CC1-CC9, A1, C1, PI1, P1)
## Audit timeline
"

# Product license at root — VP-Legal proposes and writes
if [ ! -f "$PROJECT_ROOT/LICENSE" ] && [ ! -f "$L_DIR/LICENSE" ]; then
  cat > "$L_DIR/LICENSE.proposed" <<EOF
# DRAFT — VP-Legal needs to choose one of:
#   - MIT (very permissive, common for libraries)
#   - Apache 2.0 (permissive + patent grant + contributor protection)
#   - BSL / SSPL (delayed open-source, source-available — for SaaS competing prevention)
#   - AGPL-3.0 (copyleft including network use)
#   - Proprietary (closed source)
#
# After deciding, move to <project_root>/LICENSE and remove this banner.
EOF
  echo "  + $L_DIR/LICENSE.proposed (VP-Legal: choose a license and promote to project root)" >&2
fi

echo "Legal scaffold ready at $L_DIR" >&2
