#!/usr/bin/env bash
set -euo pipefail

# init-finance-scaffold.sh - Create the project's <project_root>/finance/ tree.
#
# Outside .company/ because budgets, projections, and unit economics are
# documents the founder/CEO will want to share with investors, board, etc.
# (and probably want to commit, or .gitignore selectively).
#
# Idempotent: existing files are not overwritten.

if [ $# -lt 1 ]; then
  echo "Usage: init-finance-scaffold.sh <project-root>" >&2
  exit 1
fi

PROJECT_ROOT="$(cd "$1" && pwd)"
F_DIR="$PROJECT_ROOT/finance"

mkdir -p "$F_DIR/pnl"

DRAFT_BANNER='> **DRAFT** — Generated by Hive'"'"'s VP-Finance agent. Numbers below are
> projections/estimates, not audited financials. Review by a qualified
> accountant required before relying on this for tax, compliance, or
> investor purposes.
'

write_if_missing() {
  local path="$1" content="$2"
  [ -f "$path" ] && return
  printf '%s\n' "$content" > "$path"
  echo "  + $path" >&2
}

write_if_missing "$F_DIR/budget.md" "$DRAFT_BANNER
# Budget

## Cash position
- See finance/cash-position.json (user provides; VP-Finance reads).

## Annual operating budget (TBD)
| Category | Annual | Monthly | Notes |
|----------|--------|---------|-------|
| Infrastructure (hosting, APIs) | TBD | TBD | see vendor-costs.md |
| Salaries | TBD | TBD | if any (this is a 1-founder bootstrap by default) |
| Marketing spend | TBD | TBD | see marketing/gtm-plan.md |
| Legal & accounting | TBD | TBD | |
| Tools & SaaS | TBD | TBD | |
| Total | TBD | TBD | |
"

write_if_missing "$F_DIR/runway.json" '{
  "as_of": null,
  "cash_on_hand_usd": null,
  "monthly_burn_usd": 0,
  "monthly_revenue_usd": 0,
  "net_burn_usd": 0,
  "months_runway": null,
  "assumptions": [
    "bootstrap mode - no external funding",
    "single founder, no salary",
    "infra costs from vendor-costs.md"
  ]
}'

write_if_missing "$F_DIR/vendor-costs.md" "$DRAFT_BANNER
# Vendor Cost Ledger

| Vendor | Service | Plan | Monthly cost (USD) | Scales with | Notes |
|--------|---------|------|--------------------|-----------|-------|
| (TBD) | | | | | |

## Categories
- **Fixed**: same every month regardless of usage
- **Per-seat**: scales with team/users
- **Usage-based**: scales with API calls, storage, bandwidth
- **Per-transaction**: scales with revenue (e.g. Stripe)
"

write_if_missing "$F_DIR/unit-economics.md" "$DRAFT_BANNER
# Unit Economics

> Driven by marketing/metrics.json + marketing/pricing.md + finance/vendor-costs.md.

| Metric | Value | Source / formula |
|--------|-------|------------------|
| ARPU (avg revenue per paying user) | TBD | weighted avg of pricing tiers by mix |
| CAC (customer acquisition cost) | TBD | marketing spend / new paying users |
| LTV (lifetime value) | TBD | ARPU × (1 / monthly churn rate) |
| LTV : CAC ratio | TBD | aim for >3 |
| Gross margin | TBD | (revenue − COGS) / revenue |
| COGS per user | TBD | sum of variable costs from vendor-costs.md |
| Payback period (months) | TBD | CAC / (ARPU × gross margin) |

## Recommendations
- (none yet)
"

write_if_missing "$F_DIR/projections.json" '{
  "as_of": null,
  "scenarios": {
    "base":  {"month_3_mrr": 0, "month_12_mrr": 0, "month_24_mrr": 0, "month_36_mrr": 0},
    "bear":  {"month_3_mrr": 0, "month_12_mrr": 0, "month_24_mrr": 0, "month_36_mrr": 0},
    "bull":  {"month_3_mrr": 0, "month_12_mrr": 0, "month_24_mrr": 0, "month_36_mrr": 0}
  },
  "assumptions": [
    "starting from zero MRR",
    "growth driven by marketing/gtm-plan.md channels",
    "churn rate assumptions in unit-economics.md"
  ]
}'

write_if_missing "$F_DIR/projections.md" "$DRAFT_BANNER
# Financial Projections

See projections.json for the structured numbers. Narrative context:

## Base case
- Drivers:
- Risks:

## Bear case
- What goes wrong:

## Bull case
- What goes right:
"

write_if_missing "$F_DIR/pricing-analysis.md" "$DRAFT_BANNER
# Pricing Analysis

> For each tier in marketing/pricing.md, compute the financial reality.

| Tier | Price | Variable cost | Gross margin | Break-even users | Recommendation |
|------|-------|---------------|--------------|------------------|----------------|
| Free | \$0 | TBD | n/a | n/a | TBD: cap usage at level X to bound subsidy |
| Pro  | \$TBD | TBD | TBD | TBD | TBD |
| Team | \$TBD | TBD | TBD | TBD | TBD |
"

write_if_missing "$F_DIR/investor-summary.md" "$DRAFT_BANNER
# Investor Summary (Quarterly)

> One page suitable for investor updates, board, or fundraising prep.
> VP-Finance refreshes once per quarter or before any material outreach.

## TLDR
- One sentence on what we do.
- One sentence on traction.
- One sentence on what we need.

## Traction
- MRR: \$ — see runway.json
- Paying customers: N — see marketing/metrics.json
- Growth rate: %/mo

## Burn & runway
- Monthly burn: \$
- Months runway: N

## Unit economics
- LTV : CAC, gross margin, payback — see unit-economics.md

## What's working
## What's hard
## Asks
"

write_if_missing "$F_DIR/tax-notes.md" "$DRAFT_BANNER
# Tax & Jurisdictional Notes

> Outline only. Real tax advice requires a real accountant in your jurisdiction.

## Sales tax / VAT
- Where do we have customers?
- Where do we have nexus?

## Income tax
- Entity type:
- Jurisdiction:

## R&D credits / incentives
- Section 174 (US) — capitalization rules
- R&D tax credit (US Section 41)
- Other jurisdictions: TBD
"

# Cash position — user-provided
if [ ! -f "$F_DIR/cash-position.json" ]; then
  cat > "$F_DIR/cash-position.json" <<'JSON'
{
  "_note": "Update this with your actual cash position. VP-Finance reads it for runway calculations.",
  "as_of": null,
  "cash_on_hand_usd": null,
  "committed_runway_extension_usd": 0,
  "expected_inflows_30d_usd": 0
}
JSON
  echo "  + $F_DIR/cash-position.json (USER: fill in cash_on_hand_usd)" >&2
fi

echo "Finance scaffold ready at $F_DIR" >&2
